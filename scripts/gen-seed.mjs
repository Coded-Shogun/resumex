// Prints supabase/seed.sql from lib/seed.json: run `pnpm seed:sql`.
//
// Apply with the first admin's email (an existing Supabase account):
//   psql "$SUPABASE_DB_URL" -v admin_email=you@example.com -f supabase/seed.sql
//
// Both inserts are no-ops once data exists, so re-running never overwrites
// anything made in /admin.
import { readFileSync } from "node:fs";

const seed = JSON.stringify(JSON.parse(readFileSync(new URL("../lib/seed.json", import.meta.url), "utf8")));
if (seed.includes("$resume$")) throw new Error("seed contains the dollar-quote tag");

process.stdout.write(`-- Generated by scripts/gen-seed.mjs from lib/seed.json. Do not edit by hand.
-- Usage: psql "$SUPABASE_DB_URL" -v admin_email=you@example.com -f supabase/seed.sql

\\set ON_ERROR_STOP on
select set_config('resumex.admin_email', :'admin_email', false);

do $$
declare
  v_email text := current_setting('resumex.admin_email');
  v_id    uuid;
begin
  select id into v_id from auth.users where lower(email) = lower(trim(v_email)) limit 1;
  if v_id is null then
    raise exception 'No Supabase account for %. Create the user in Supabase Studio first.', v_email;
  end if;
  insert into public.resume_users (user_id, display_name, role, created_by)
  values (v_id, '', 'admin', v_id)
  on conflict (user_id) do update set role = 'admin', active = true;
end;
$$;

insert into public.resume_versions (label, document, is_active, activated_at)
select 'CV 2026 (initial)', $resume$${seed}$resume$::jsonb, true, now()
where not exists (select 1 from public.resume_versions);
`);
